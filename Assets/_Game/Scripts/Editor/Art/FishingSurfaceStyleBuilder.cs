using Fishing.Game;
using UnityEditor;
using UnityEngine;

namespace Fishing.Editor
{
    /// <summary>Binds one shared deformation material without rebuilding environment art or scene instances.</summary>
    public static class FishingSurfaceStyleBuilder
    {
        /// <summary>Prepares the existing environment for the demo-style surface presentation.</summary>
        [MenuItem("Fishing/Prepare demo surface style")]
        public static string Prepare()
        {
            if (EditorApplication.isPlaying) throw new System.InvalidOperationException("Stop Play before preparing surface style.");
            const string path = "Assets/_Game/Prefabs/Environment.prefab";
            var root = PrefabUtility.LoadPrefabContents(path);
            try
            {
                Configure(root);
                PrefabUtility.SaveAsPrefabAsset(root, path); AssetDatabase.SaveAssets();
            }
            finally { PrefabUtility.UnloadPrefabContents(root); }
            return "Bound one shared deformation material; original artwork and physics bindings retained.";
        }
        /// <summary>Retains the same surface binding when the environment is regenerated by its existing builder.</summary>
        public static void Configure(GameObject root)
        {
            var shader = Shader.Find("Fishing/Surface Deformed Lit");
            if (shader == null) throw new System.InvalidOperationException("Surface deformation shader is not imported.");
            const string materialPath = "Assets/_Game/Art/Materials/SurfaceDeform.mat";
            var material = AssetDatabase.LoadAssetAtPath<Material>(materialPath);
            if (material == null) { material = new Material(shader); AssetDatabase.CreateAsset(material, materialPath); }
            var data = new SerializedObject(root.GetComponent<FishingSceneView>());
            data.FindProperty("deformMaterial").objectReferenceValue = material; data.ApplyModifiedPropertiesWithoutUndo();
        }
    }
}
